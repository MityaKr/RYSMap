package works.repka.rysmap.tile;

/**
 * Когда тайлы можно печь и когда испечённые надо отпустить, по таблице цветов (баг 19.11, 0.2.8).
 *
 * <p>Таблица цветов строится порциями в главном потоке после входа в мир (на RepYS около 10 секунд). Раньше миникарта
 * успевала заказать регионы вокруг игрока, пекарь красил их пустой таблицей (все блоки «неизвестные»: серый со
 * штриховкой, видна только вода), а первую смену версии таблицы сессия пропускала. Текстуры под миникартой рисуются
 * каждый кадр и сами не отпускаются, поэтому столбец регионов игрока оставался серым до перезахода; чанки, снятые
 * сканером позже, ложились поверх уже цветными.
 *
 * <p>Теперь: пока таблица ни разу не построена, тайлы не заказываются; любая смена версии после этого, первая тоже,
 * отпускает текстуры. Чистая Java для модульного теста, владелец главный поток.
 */
public final class ColorGate {
    /** Что делать с тайлами в этот тик. */
    public enum Step {
        /** Таблица ещё не построена: новые тайлы не заказывать. */
        HOLD,
        /** Версия таблицы сменилась: отпустить текстуры, следующие кадры закажут их заново. */
        DROP,
        /** Ничего не менялось. */
        KEEP
    }

    private boolean seenAny;
    private long seen;

    /**
     * @param built   таблица хоть раз построена (при перестройке после смены ресурспаков старая служит пекарю)
     * @param version версия таблицы ({@link MapColors#version()})
     */
    public Step update(boolean built, long version) {
        if (!built) return Step.HOLD;
        if (seenAny && seen == version) return Step.KEEP;
        seenAny = true;
        seen = version;
        return Step.DROP;
    }
}
